/**@type {Map<LAPUnmapped, `type ${LAPUnmapped} = number & {${LAPUnmapped}?:never}`>} */
const taggedTypeMap = new Map()
/**@param {LibApiParameter|ConstantType} v */
const get_param_type_str = (v) => {
	if (v in paramsTypeMap) return paramsTypeMap[/**@type {LAPMapped}*/ (v)]
	const vv = /**@type {Exclude<LibApiParameter, LAPMapped>}*/ (v)
	if (typeof v != 'number' && !taggedTypeMap.has(vv))
		// remove ? to error on type cast
		taggedTypeMap.set(vv, `type ${vv} = number & {${vv}?:never}`)
	return vv
}
