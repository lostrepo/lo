//#region fs stuff
function checkMode(val, mode) {
	return (val & lo.core.S_IFMT) === mode
}

function is_file(path) {
	let MODE_WORD = 6
	if (lo.core.os === 'linux' && lo.core.arch === 'arm64') {
		MODE_WORD = 4
	} else if (lo.core.os === 'mac') {
		MODE_WORD = 1
	}
	const stat = new Uint8Array(160)
	const stat32 = new Uint32Array(stat.buffer)
	const fd = lo.core.open(path, lo.core.O_RDONLY, 0)
	if (fd <= 2) return false
	if (lo.core.fstat(fd, lo.get_address(stat)) !== 0) return false
	lo.core.close(fd)
	return checkMode(stat32[MODE_WORD], lo.core.S_IFREG)
}

function readEntry(handle) {
	const u8 = new Uint8Array(19)
	const dir_view = new DataView(u8.buffer)
	lo.read_memory(lo.get_address(u8), handle, 19)
	const d_ino = dir_view.getUint32(0, true)
	const d_off = dir_view.getUint32(8, true)
	const d_reclen = dir_view.getUint16(16, true)
	const d_type = u8[18]
	const name = lo.utf8_decode(
		handle + 19,
		lo.core.strnlen(handle + 19, lo.core.NAME_MAX),
	)
	return { d_ino, d_off, d_reclen, d_type, name }
}

/** @type {(path: string) => string[]} */
function list_children(path) {
	const { opendir, readdir } = lo.core
	const dir = opendir(path)
	const children = []
	if (!dir) return children
	let next = readdir(dir)
	lo.assert(next)
	while (next) {
		const entry = readEntry(next)
		if (!(entry.name === '..' || entry.name === '.')) {
			children.push(`${path}/${entry.name}`)
		}
		next = readdir(dir)
	}
	lo.assert(lo.core.closedir(dir) === 0)
	return children
}
