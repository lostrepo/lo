export const typedef_block = {
	first_line: (name) => `//#region ${name}`,
	last_line: (name) => `//#endregion ${name}`,
	block_regex: (name) => {
		const [start, end] = [
			typedef_block.first_line(name),
			typedef_block.last_line(name),
		]
		return new RegExp(
			start.replace(/([\?\\\/\.])/g, '\\$1')
				+ '[\\s\\S]+'
				+ end.replace(/([\?\\\/\.])/g, '\\$1'),
			'gmi',
		)
	},
	wrap: async (
		name,
		/** @type {string | (() => string)} */ fnOrString,
	) => `${typedef_block.first_line(name)}
${await Promise.resolve(typeof fnOrString === 'string' ? fnOrString : fnOrString())}
${typedef_block.last_line(name)}`,
	replace_block: async (
		/** @type {string} */ source,
		name,
		/** @type {string | (() => string)} */ fnOrString,
		appendBefore = source.length,
	) => {
		const new_typedef_str = await typedef_block.wrap(name, fnOrString)
		// nothing to change
		if (source.includes(new_typedef_str)) return source
		const regex = typedef_block.block_regex(name)
		const has_typedef_block = regex.test(source)
		return has_typedef_block
			? source.replace(regex, new_typedef_str)
			: appendBefore >= source.length
				? `${source}\n${new_typedef_str}`
				: `${source.substring(0, appendBefore)}${new_typedef_str}
${source.substring(appendBefore, source.length)}`
	},
	replace_line: (/** @type {string} */ source, name, is_first = false) => {
		const { first_line, last_line } = typedef_block
		const line = is_first ? first_line(name) : last_line(name)
		const has_line = source.indexOf(line) !== -1
		return has_line ? source : `${source}\n${line}`
	},
	remove_line: (/** @type {string} */ source, name, is_first = false) => {
		const { first_line, last_line } = typedef_block
		const line = is_first ? first_line(name) : last_line(name)
		const has_line = source.indexOf(line) !== -1
		return !has_line
			? source
			: source.replace(`\n${line}`, '').replace(line, '')
	},
	remove_block: (/** @type {string} */ source, name) => {
		const { block_regex, remove_line } = typedef_block
		const regex = block_regex(name)
		if (regex.test(source)) {
			source = source.replace(regex, '')
			if (regex.test(source)) console.log(name)
		} else {
			source = remove_line(source, name, true)
			source = remove_line(source, name, false)
		}
		return source
	},
	line_pos: (name, is_first = false, /** @type {string} */ source) => {
		const { first_line, last_line } = typedef_block
		const line = is_first ? first_line(name) : last_line(name)
		return source.indexOf(line)
	},
	find_all_block_names: (/** @type {string} */ source) => {
		const regex = /^\/\/#(end){0,1}region\s+([^\n]+)\s*$/gim
		/** @type {string[]} */
		const block_names = []
		do {
			const match = regex.exec(source)
			if (!match) break
			const block_name = match[2]
			if (!block_names.includes(block_name)) block_names.push(block_name)
		} while (true)
		return block_names
	},
}
