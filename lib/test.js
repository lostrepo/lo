/**@param {LibApi} api */
const get_lo_lib_api_strings = (api) =>
	Object.keys(api).map((k) => {
		let res = ''
		const api_k = api[k]
		if ('declare_only' in api_k) return res
		const { parameters, result, arch, jsdoc, man, optional } = api_k
		// arch is defined and doesn't match
		if (arch && arch.length && !arch.includes(lo.core.arch)) return res
		const params_strs = parameters.map((v, i) =>
			paramWithType(`p${i}`, optional?.[i], v),
		)
		const jsdoc_str = `${jsdoc ? jsdoc + '\n' : ''}`
		const man_str = `${man ? `// man: ${man}\n` : ''}`
		const ret_str = get_param_type_str(result)
		return `${jsdoc_str}${man_str}  ${k}(${params_strs}): ${ret_str};\n`
	})

/**@param {LibConstants} constants */
const get_lo_lib_constants_strings = (constants) =>
	Object.keys(constants).map(
		(k) => `  ${k}: ${get_param_type_str(constants[k])};\n`,
	)

/**@param {string[]} structs */
const get_lo_lib_structs_strings = (structs) =>
	structs.map((s) => `  struct_${s.split(' ').join('_')}_size: number;\n`)

/**@param {LibApiExports} def */
const get_lo_lib_obj_props_strings = (def) => {
	const platform = def[lo.core.os]
	const structs = [...(def.structs || []), ...(platform?.structs || [])]
	const constants = { ...def.constants, ...platform?.constants }
	const api = { ...def.api, ...platform?.api }
	return [
		...get_lo_lib_api_strings(api),
		...get_lo_lib_constants_strings(constants),
		...get_lo_lib_structs_strings(structs),
	]
}

/**@param {LibApiExports[]} lib_exports */
const get_lo_libs_string = (lib_exports) => {
	let native_libs_str = ''
	for (let i = 0; i < lib_exports.length; i++) {
		const def = lib_exports[i]
		const lib_name = def.lib_name
		const decl_string = def.name
		const decl_props_strings = get_lo_lib_obj_props_strings(def)
		const decl_final_string = `  ${lib_name}: {
  ${decl_string}: {
    ${decl_props_strings.join('    ')}
    }
  }`
		native_libs_str = `${native_libs_str}\n${decl_final_string}`
	}

	return `interface NativeLibs {\n${native_libs_str}\n}`
}

