const default_lib_dir_name = 'lib'
const api_file_name = 'api.js'

const get_apis = (lib_dir = default_lib_dir_name) => {
	const filter_js_ts_files = (path = '') => path && !/\.[jt]s/.test(path)
	const modules_set = new Set()
	/**@type {LibApiMeta[]}*/
	const apis = []
	const builtins = lo.builtins()
	const add_api = (local = false, path = '') => {
		const module_name = path.replace(/^.*\/([^\/]+)$/, '$1')
		if (modules_set.has(module_name)) return
		const api_js_path = `${path}/${api_file_name}`
		// check binary
		// check disk
		if (!builtins.includes(api_js_path) && !is_file(api_js_path)) return
		modules_set.add(module_name)
		apis.push({ module_name, path: api_js_path, local })
	}

	list_children(`${lo.getcwd()}/${lib_dir}`)
		.filter(filter_js_ts_files)
		.forEach(add_api.bind(null, true))

	const home = lo.getenv('LO_HOME')
	if (home && home != lib_dir)
		list_children(`${home}/${default_lib_dir_name}`)
			.filter(filter_js_ts_files)
			.forEach(add_api.bind(null, false))

	return apis
}

